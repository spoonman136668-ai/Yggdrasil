"""O22-V original-source 3-selected-action delayed progress, FIT-only.

Read immutable C28 archive of 805 real original chosen-action before/after
receipts. No original world reset/step, novel source-family or held-out DEV.
Observed delayed return is generated by ACTUALLY chosen subsequent actions,
never by an unexecuted candidate's alleged counterfactual future.
"""
from __future__ import annotations
import argparse
from collections import defaultdict
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import time
import zipfile

from research.optimizer_o22v.delayed_cells import (
    DelayedNativeCells,FittedRidge9,phi,canonical
)

HERE=Path(__file__).resolve().parent
P=json.loads((HERE/"PREREG.json").read_text())
C28=P["immutable_source_fit"]
HORIZON=P["n_selected_source_future_actions"]


def _dist(s):
    return abs(s["goal_x"]-s["x"])+abs(s["goal_y"]-s["y"])


def load_original_c28(raw):
    if hashlib.sha256(raw).hexdigest()!=C28["zip_sha256"]:
        raise ValueError("O22V_ORIGINAL_C28_ZIP_IDENTITY_DRIFT")
    z=zipfile.ZipFile(io.BytesIO(raw))
    if z.testzip() is not None or set(z.namelist())!={
        "comparison.json","original-fit-1.json","original-fit-2.json"}:
        raise ValueError("O22V_ORIGINAL_C28_ARCHIVE_INVALID")
    a,b=[json.loads(z.read(n)) for n in ("original-fit-1.json","original-fit-2.json")]
    comparison=json.loads(z.read("comparison.json"))
    if (a["source_fit_event_ledger_sha256"]!=comparison["original_source_fit_event_sha256"]
        or a["source_fit_event_ledger_sha256"]!=b["source_fit_event_ledger_sha256"]
        or len(a["source_fit_events"])!=C28["ledger_events"]):
        raise ValueError("O22V_C28_LEDGER_SOURCE_DRIFT")
    sha=hashlib.sha256(canonical(a["source_fit_events"])).hexdigest()
    if sha!=a["source_fit_event_ledger_sha256"] or a["source_fit_events"]!=b["source_fit_events"]:
        raise ValueError("O22V_TWO_ORIGINAL_SOURCE_PROCESS_DIFFER")
    if (a["original_new_dev_episodes"]!=0 or a["protected_first_use_episodes"]!=0
        or b["original_new_dev_episodes"]!=0 or b["protected_first_use_episodes"]!=0):
        raise ValueError("O22V_UNAUTHORIZED_SOURCE_ROLE")
    episodes=defaultdict(list)
    for e in a["source_fit_events"]:
        key=(e["family"],e["seed"])
        if e["family"] not in C28["families"]:
            raise ValueError("O22V_UNFROZEN_SOURCE_FAMILY")
        expected=(P["train_source_FIT_seeds"][e["family"]]+
                  P["internal_check_source_FIT_seeds"][e["family"]])
        if e["seed"] not in expected:
            raise ValueError("O22V_SOURCE_FIT_ROLE_DRIFT")
        st=e["before"];aft=e["returned_after"]
        phi(st);phi(aft)
        if type(e["chosen_action"]) is not int or e["chosen_action"] not in (0,1,2):
            raise ValueError("O22V_SOURCE_SELECTED_ACTION")
        if (type(e["returned_reward"]) not in (int,float)
            or type(e["terminated"]) is not bool or type(e["truncated"]) is not bool):
            raise ValueError("O22V_SOURCE_OUTCOME_GRAMMAR")
        prev=episodes[key][-1] if episodes[key] else None
        if e["step"] != len(episodes[key]) or (prev is not None and
            (prev["returned_after"]["x"],prev["returned_after"]["y"],
             prev["returned_after"]["direction"]) !=
            (st["x"],st["y"],st["direction"])):
            raise ValueError("O22V_SOURCE_ACTION_TIME_OR_POSE_DRIFT")
        if prev is not None and (prev["terminated"] or prev["truncated"]):
            raise ValueError("O22V_SOURCE_EVENT_AFTER_TERMINAL")
        episodes[key].append(e)
    count={f:0 for f in C28["families"]}
    for (family,seed),rows in episodes.items():
        count[family]+=1
        published=next((q for q in a["source_fit_episodes"]
                       if q["family"]==family and q["seed"]==seed),None)
        if (published is None or published["actions"]!=len(rows) or
            published["source_public_event_sha256"]!=hashlib.sha256(canonical(rows)).hexdigest()):
            raise ValueError("O22V_PER_ORIGINAL_EPISODE_SOURCE_SHA_DRIFT")
    if any(count[f]!=12 for f in count):
        raise ValueError("O22V_C28_ORIGINAL_EPISODES_MISSING")
    return episodes,sha


def actual_windows(episodes):
    out=[]
    for (family,seed),rows in episodes.items():
        for t in range(len(rows)-HORIZON+1):
            r0=rows[t]
            window=rows[t:t+HORIZON]
            if any(e["terminated"] or e["truncated"] for e in window[:-1]):
                raise ValueError("O22V_TERMINAL_CROSSED_BY_FORECAST")
            end=window[-1]["returned_after"]
            observed=max(-1.,min(1.,(_dist(r0["before"])-_dist(end))/float(HORIZON)))
            out.append({"family":family,"seed":seed,"step":t,
                        "before":r0["before"],"selected_action":r0["chosen_action"],
                        "observed_three_ACTUALLY_SELECTED_actions":[e["chosen_action"] for e in window],
                        "observed_goal_distance_before":_dist(r0["before"]),
                        "observed_goal_distance_after_three":_dist(end),
                        "observed_selected_sequence_progress":observed})
    return out


def fit_windows(rows,model,shuffle_actions=False):
    t0=time.process_time()
    for r in rows:
        action=r["selected_action"]
        if shuffle_actions:action=1-action if action in (0,1) else action
        model.learn(r["before"],action,r["observed_selected_sequence_progress"])
    if isinstance(model,FittedRidge9):
        model.finalize()
    return round(time.process_time()-t0,8)


def scored(rows,model):
    tab={}
    for r in rows:
        prediction=model.predict(r["before"],r["selected_action"])
        truth=r["observed_selected_sequence_progress"]
        if not -1.00001<=prediction<=1.00001:
            raise ValueError("O22V_INVALID_LEARNED_PROGRESS")
        err=(prediction-truth)**2
        keys=["all",r["family"],"action_"+str(r["selected_action"]),
              r["family"]+"|action_"+str(r["selected_action"])]
        for k in keys:
            st=tab.setdefault(k,{"n":0,"sum_error":0.,"mean_true":0.,"nonzero":0})
            st["n"]+=1;st["sum_error"]+=err;st["mean_true"]+=truth
            st["nonzero"]+=int(truth!=0)
    return {k:{"n":v["n"],"mse":round(v["sum_error"]/v["n"],9),
               "average_observed_progress":round(v["mean_true"]/v["n"],9),
               "nonzero_observed_progress":v["nonzero"]}
            for k,v in sorted(tab.items())}


def new_process_checkpoint(model,b):
    cp=model.checkpoint()
    local=type(model).restore(cp)
    if local.checkpoint()!=cp:
        raise ValueError("O22V_SNAPSHOT_MISMATCH")
    for action in (0,1,2):
        if model.predict(b,action)!=local.predict(b,action):
            raise ValueError("O22V_COLD_PREDICTION_MISMATCH")
    program=(
        "import json,sys;"
        "from research.optimizer_o22v.delayed_cells import DelayedNativeCells,FittedRidge9;"
        "p=json.loads(sys.stdin.buffer.read());"
        "m=globals()[p['class']].restore(p['state'].encode());"
        "print(json.dumps({'pred':[m.predict(p['public'],a) for a in (0,1,2)],"
        "'proposal':m.propose(p['public']),'events':m.events}))"
    )
    blob=canonical({"class":type(model).__name__,"state":cp.decode(),"public":b})
    env=dict(os.environ,PYTHONPATH=str(HERE.parents[2]),PYTHONDONTWRITEBYTECODE="1")
    child=subprocess.run([sys.executable,"-B","-c",program],input=blob,
        capture_output=True,timeout=20,cwd=HERE.parents[2],env=env)
    if child.returncode:
        raise ValueError("O22V_FRESH_PYTHON_PROCESS_FAILED:"+child.stderr.decode())
    got=json.loads(child.stdout)
    if got!={"pred":[model.predict(b,a) for a in (0,1,2)],
             "proposal":model.propose(b),"events":model.events}:
        raise ValueError("O22V_COLD_SOURCE_ACTION_DIFFERENCE")
    return len(cp)


def proposal_audit(rows,models):
    counts={"states_considered":len(rows),"native_active_proposals":0,
            "native_vs_original_zero_changed":0,
            "native_vs_shuffled_changed":0,
            "native_vs_full9_ridge_changed":0,
            "native_vs_no_action_ridge_changed":0}
    for r in rows:
        b=r["before"]
        active=models["native"].propose(b)
        if active is not None:
            counts["native_active_proposals"]+=1
        if active!=None:
            counts["native_vs_original_zero_changed"]+=1
        for label,key in (("native_vs_shuffled_changed","shuffled_native"),
                          ("native_vs_full9_ridge_changed","ridge9"),
                          ("native_vs_no_action_ridge_changed","no_action_ridge9")):
            counts[label]+=int(active!=models[key].propose(b))
    return counts


def main():
    import resource  # POSIX hosted original FIT audit only; Windows unit imports remain legal
    parser=argparse.ArgumentParser()
    parser.add_argument("--source-zip",type=Path,required=True)
    parser.add_argument("--out",type=Path,required=True)
    args=parser.parse_args()
    episodes,ledger=load_original_c28(args.source_zip.read_bytes())
    examples=actual_windows(episodes)
    train=[v for v in examples if
           v["seed"] in P["train_source_FIT_seeds"][v["family"]]]
    internal=[v for v in examples if
              v["seed"] in P["internal_check_source_FIT_seeds"][v["family"]]]
    if len(train)==0 or len(internal)==0 or len(train)+len(internal)!=len(examples):
        raise ValueError("O22V_AUTHENTIC_FIT_SPLIT_MISMATCH")
    models={"native":DelayedNativeCells(),"ridge9":FittedRidge9(True),
            "no_action_ridge9":FittedRidge9(False),
            "shuffled_native":DelayedNativeCells()}
    cpu={}
    for name,m in models.items():
        cpu[name]=fit_windows(train,m,name=="shuffled_native")
        if m.events!=len(train):
            raise ValueError("O22V_SOURCE_TRAIN_EQUALITY_FAIL")
    reports={k:scored(internal,v) for k,v in models.items()}
    sizes={k:new_process_checkpoint(v,internal[0]["before"])
           for k,v in models.items()}
    proposals=proposal_audit(internal,models)
    n=reports["native"]["all"]["mse"]
    r=reports["ridge9"]["all"]["mse"]
    if n>=r:
        verdict="NO_GO_NATIVE_DELAYED_VALUE_PREDICTION_VS_FULL9_RIDGE"
    elif any(reports["native"][f]["mse"]>=reports["ridge9"][f]["mse"]
             for f in C28["families"]):
        verdict="NO_GO_NATIVE_DELAYED_VALUE_NOT_BETTER_BOTH_FAMILIES"
    else:
        verdict="INTERNAL_FIT_EXPLORATORY_MULTI_STEP_NOT_REAL_ACTION_VALUE_GO"
    result={
        "schema":P["schema"],
        "authentic_source_original":P["original_farama"],
        "authentic_original_C28_ledger_sha256":ledger,
        "source_episode_count":len(episodes),
        "original_physically_selected_source_events":C28["ledger_events"],
        "selected_action_future_horizon":HORIZON,
        "real_source_FIT_train_episodes":16,
        "real_source_internal_FIT_check_episodes_ALREADY_EXPOSED":8,
        "train_action_conditioned_three_step_windows":len(train),
        "internal_FIT_three_step_windows":len(internal),
        "observed_consequences_from_real_selected_continuations_only":True,
        "held_check_is_NOT_independent_DEV_or_protected":True,
        "learned_progress_MSE_by_family_and_selected_action":reports,
        "hypothetical_proposals_NOT_executed_alternative_actions":proposals,
        "checkpoint_bytes_cold_full_state":sizes,
        "model_fitting_cpu_seconds":cpu,
        "process_python_peak_rss_kib":resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
        "true_unselected_action_source_return":"UNKNOWN_NOT_OBSERVED",
        "full_original_world_policy_goal_advantage":"NOT_TESTED",
        "original_source_new_FIT_DEV_protected_actions":0,
        "verdict":verdict
    }
    args.out.write_bytes(canonical(result)+b"\n")
    print("O22V_AUTHENTIC_C28_TWO_PROCESS_FULL_SOURCE_SHA=PASS",flush=True)
    print("O22V_EQUAL_TRAINED_REAL_SELECTED_THREE_STEP_WINDOWS="+str(len(train)),flush=True)
    print("O22V_INTERNAL_ALREADY_EXPOSED_FIT_WINDOWS="+str(len(internal)),flush=True)
    for key in sorted(reports):
        print("O22V_"+key.upper()+"_PROGRESS_MSE="+str(reports[key]["all"]["mse"]),flush=True)
    print("O22V_HYPOTHETICAL_LOCAL_PROPOSALS="+json.dumps(proposals,sort_keys=True),flush=True)
    print("O22V_COLD_ALL_LEARNED_MODELS=PASS",flush=True)
    print("O22V_SCIENTIFIC_DECISION="+verdict,flush=True)
    print("O22V_ORIGINAL_ENVIRONMENT_NEW_ACTIONS=ZERO",flush=True)


if __name__=="__main__":
    main()
