def features(a, previous, context):
    if any(type(x) is not int for x in (a, previous, context)) or not (0 <= a < 256 and 0 <= previous < 256 and 0 <= context < 4):
        raise ControlRejected("F49_INVALID_CONVENTIONAL_FEATURE")
    return np.array([float((a >> j) & 1) for j in range(8)]
                    + [float((previous >> j) & 1) for j in range(8)]
                    + [float((context >> j) & 1) for j in range(2)], dtype=np.float64)


def pair_features(tr):
    a, b, c = _check_trajectory(tr)
    return np.stack((features(a,0,c), features(b,a,c)), axis=0)


def permitted_source_training(size):
    """All source-bank programs and all 64 TRAIN trajectories; no DEV target."""
    world.freeze()
    if type(size) is not int or size not in world.BANK_SIZES:
        raise ControlRejected("F49_CONVENTIONAL_BANK_INVALID")
    n = size * 64 * 2
    x = np.empty((n,18), dtype=np.float64)
    y = np.empty(n, dtype=np.float64)
    offset = 0
    for law_index in range(size):
        rows = world.source_training_row(size, law_index)
        if len(rows) != 64:
            raise ControlRejected("F49_TRAIN_SOURCE_INCOMPLETE")
        for tr, observed in rows:
            observed = _check_bits(observed)
            x[offset:offset+2] = pair_features(tr)
            y[offset:offset+2] = observed
            offset += 2
    if offset != n:
        raise ControlRejected("F49_TRAIN_SOURCE_COUNT_MISMATCH")
    return x, y


def split_train_validation(x, y):
    if x.ndim != 2 or x.shape[1] != 18 or y.shape != (len(x),) or len(x) < 20:
        raise ControlRejected("F49_SOURCE_TRAIN_SHAPE_INVALID")
    indices = np.random.default_rng(11).permutation(len(x))
    count = len(x) // 10
    val, train = indices[:count], indices[count:]
    return x[train], y[train], x[val], y[val]


def _sigmoid(z):
    z=np.clip(z, -60, 60)
    return 1.0/(1.0+np.exp(-z))


def _loss(prob, target):
    p=np.clip(prob,1e-12,1-1e-12)
    return float(np.mean(-target*np.log(p)-(1-target)*np.log(1-p)))


class Logistic:
    """Explicit deterministic full-batch Newton solver (L2 = 0.001)."""

    def __init__(self):
        self.w=np.zeros(19,dtype=np.float64)
        self.steps=0
        self.prediction_accesses=0

    def clone(self):
        other=Logistic()
        other.w=self.w.copy()
        other.steps=self.steps
        return other

    def probabilities(self, x):
        self.prediction_accesses+=len(x)
        return _sigmoid(x@self.w[:18]+self.w[18])

    def fit(self,x,y,*,max_iter=500,tolerance=1e-8):
        if x.ndim!=2 or x.shape[1]!=18 or y.shape!=(len(x),) or not len(x):
            raise ControlRejected("F49_LOGISTIC_FIT_INVALID")
        if max_iter<1 or max_iter>500 or tolerance!=1e-8:
            raise ControlRejected("F49_LOGISTIC_SOLVER_DRIFT")
        xx=np.column_stack((x,np.ones(len(x))))
        penalty=np.full(19,0.001)
        penalty[-1]=0.0
        iterations=0
        for _ in range(max_iter):
            p=_sigmoid(xx@self.w)
            gradient=(xx.T@(p-y))/len(y)+penalty*self.w
            if float(np.max(np.abs(gradient)))<tolerance:
                break
            diag=np.maximum(p*(1-p),1e-12)
            hessian=(xx.T@(xx*diag[:,None]))/len(y)+np.diag(penalty+1e-10)
            delta=np.linalg.solve(hessian,gradient)
            obj=_loss(p,y)+0.5*float(np.dot(penalty*self.w,self.w))
            step=1.0
            while step>2**-30:
                proposed=self.w-step*delta
                prob=_sigmoid(xx@proposed)
                loss=_loss(prob,y)+0.5*float(np.dot(penalty*proposed,proposed))
                if loss<=obj+1e-12:
                    self.w=proposed
                    break
                step*=0.5
            if step<=2**-30:
                break
            iterations+=1
        self.steps+=iterations
        return {"iterations":iterations,"train_loss":_loss(_sigmoid(xx@self.w),y),
                "max_gradient":float(np.max(np.abs((xx.T@(_sigmoid(xx@self.w)-y))/len(y)+penalty*self.w)))}


class MLP:
    """Two hidden 64x64 ReLU layers, Bernoulli output and Adam(0.001)."""

    def __init__(self,seed=11):
        rng=np.random.default_rng(seed)
        self.params=[
            rng.normal(0,np.sqrt(2/18),(18,64)),
            np.zeros(64),
            rng.normal(0,np.sqrt(2/64),(64,64)),
            np.zeros(64),
            rng.normal(0,np.sqrt(2/64),(64,1)),
            np.zeros(1)]
        self.m=[np.zeros_like(v) for v in self.params]
        self.v=[np.zeros_like(v) for v in self.params]
        self.steps=0
        self.prediction_accesses=0

    def clone(self):
        other=MLP()
        other.params=[x.copy() for x in self.params]
        other.m=[x.copy() for x in self.m]
        other.v=[x.copy() for x in self.v]
        other.steps=self.steps
        return other

    def _forward(self,x):
        w,b,u,c,v,d=self.params
        h1=np.maximum(x@w+b,0)
        h2=np.maximum(h1@u+c,0)
        return h1,h2,_sigmoid((h2@v+d).reshape(-1))

    def probabilities(self,x):
        if x.ndim!=2 or x.shape[1]!=18:
            raise ControlRejected("F49_MLP_INPUT_INVALID")
        self.prediction_accesses+=len(x)
        return self._forward(x)[2]

    def _train_batch(self,x,y):
        w,b,u,c,v,d=self.params
        h1,h2,p=self._forward(x)
        dz=((p-y)/len(y))[:,None]
        grads=[None]*6
        grads[4]=h2.T@dz
        grads[5]=dz.sum(axis=0)
        dh2=(dz@v.T)*(h2>0)
        grads[2]=h1.T@dh2
        grads[3]=dh2.sum(axis=0)
        dh1=(dh2@u.T)*(h1>0)
        grads[0]=x.T@dh1
        grads[1]=dh1.sum(axis=0)
        self.steps+=1
        for i,g in enumerate(grads):
            self.m[i]=0.9*self.m[i]+0.1*g
            self.v[i]=0.999*self.v[i]+0.001*(g*g)
            mh=self.m[i]/(1-0.9**self.steps)
            vh=self.v[i]/(1-0.999**self.steps)
            self.params[i]-=0.001*mh/(np.sqrt(vh)+1e-8)

    def pretrain(self,x,y,xval,yval,*,max_epochs=200,patience=20):
        if (max_epochs<1 or max_epochs>200 or patience<1 or patience>20
            or x.ndim!=2 or x.shape[1]!=18 or y.shape!=(len(x),)
            or xval.ndim!=2 or xval.shape[1]!=18 or yval.shape!=(len(xval),)):
            raise ControlRejected("F49_MLP_PRETRAIN_DRIFT")
        rng=np.random.default_rng(11)
        best=float("inf")
        saved=None
        waiting=0
        epochs=0
        for epoch in range(max_epochs):
            for batch in np.array_split(rng.permutation(len(x)),
                                        (len(x)+127)//128):
                self._train_batch(x[batch],y[batch])
            epochs=epoch+1
            val=_loss(self.probabilities(xval),yval)
            if val < best-1e-12:
                best,waiting=val,0
                saved=([z.copy() for z in self.params],
                       [z.copy() for z in self.m],
                       [z.copy() for z in self.v],self.steps)
            else:
                waiting+=1
                if waiting>=patience:
                    break
        self.params,self.m,self.v,self.steps=saved
        return {"epochs":epochs,"best_validation_loss":best,
                "optimizer_steps":self.steps}

    def adapt_public(self,x,y):
        if x.shape!=(len(y),18) or not 0<len(x)<=64:
            raise ControlRejected("F49_MLP_TARGET_OBSERVATION_INVALID")
        # Exactly sixteen bounded target-only updates, no replayed TRAIN examples.
        for _ in range(16):
            self._train_batch(x,y)


class Pretrained:
    """Source-trained model identity and costs, reusable only within same bank size."""

    def __init__(self,kind,size,model,source_observations,source_seconds,fit_details):
        if (kind not in ("conventional_mlp","conventional_logistic")
            or type(size) is not int or size not in world.BANK_SIZES
            or source_observations != 128*size):
            raise ControlRejected("F49_SOURCE_TRAINING_INCOMPLETE")
        if type(model) is not (MLP if kind=="conventional_mlp" else Logistic):
            raise ControlRejected("F49_WRONG_SOURCE_MODEL")
        self.kind,self.size,self.model=kind,size,model
        self.source_observations=source_observations
        self.source_seconds=source_seconds
        self.fit_details=fit_details

    def clone_model(self):
        return self.model.clone()


def full_source_fit(kind,size):
    """Only approved real pretraining entry; parameters are protocol-locked."""
    world.freeze()
    if kind not in ("conventional_mlp","conventional_logistic"):
        raise ControlRejected("F49_WRONG_CONVENTIONAL_ARM")
    t0=perf_counter()
    x,y=permitted_source_training(size)
    if kind=="conventional_mlp":
        model=MLP(seed=11)
        train,ys,val,yval=split_train_validation(x,y)
        receipt=model.pretrain(train,ys,val,yval,max_epochs=200,patience=20)
    else:
        model=Logistic()
        receipt=model.fit(x,y,max_iter=500,tolerance=1e-8)
    return Pretrained(kind,size,model,len(y),perf_counter()-t0,receipt)


class ConventionalArm:
    """Each arm has its own public actions, isolated pretrained copy and memory."""

    def __init__(self,pretrained,seed):
        world.freeze()
        if not isinstance(pretrained,Pretrained) or type(seed) is not int or seed not in world.SEEDS:
            raise ControlRejected("F49_CONVENTIONAL_ARM_INVALID")
        self.kind,self.size,self.seed=pretrained.kind,pretrained.size,seed
        self.model=pretrained.clone_model()
        self.pool=world.public_query_pool(self.size,seed)
        self.used=[]
        self.events=[]
        self.awaiting=None
        self.adaptation_seconds=0.0
        self.selector_seconds=0.0
        self.pretraining_seconds=pretrained.source_seconds
        self.source_observations=pretrained.source_observations

    def select(self):
        if self.awaiting is not None or len(self.used)>=MAX_BUDGET:
            raise ControlRejected("F49_QUERY_STATE_INVALID")
        t0=perf_counter()
        remaining=[i for i in range(len(self.pool)) if i not in self.used]
        allfeatures=np.concatenate([pair_features(self.pool[i]) for i in remaining])
        probs=self.model.probabilities(allfeatures).reshape(len(remaining),2)
        score=np.sum(-(probs*np.log2(np.clip(probs,1e-12,1))
                       +(1-probs)*np.log2(np.clip(1-probs,1e-12,1))),axis=1)
        chosen=int(np.argmax(score))
        self.awaiting=remaining[chosen]
        self.selector_seconds+=perf_counter()-t0
        return self.awaiting,self.pool[self.awaiting]

    def observe(self,index,outcome):
        if type(index) is not int or self.awaiting!=index or index in self.used:
            raise ControlRejected("F49_UNAUTHORIZED_OR_REPLAYED_PUBLIC_EVENT")
        pair=_check_bits(outcome)
        t0=perf_counter()
        self.events.append((self.pool[index],pair))
        x=np.concatenate([pair_features(tr) for tr,_ in self.events])
        y=np.array([bit for _,out in self.events for bit in out],dtype=np.float64)
        if self.kind=="conventional_mlp":
            self.model.adapt_public(x,y)
        else:
            # Source-fitted initialization is retained, target refit uses target public bits only.
            self.model.fit(x,y,max_iter=500,tolerance=1e-8)
        self.used.append(index)
        self.awaiting=None
        self.adaptation_seconds+=perf_counter()-t0

    def probability(self,tr):
        return tuple(map(float,self.model.probabilities(pair_features(tr))))

    @property
    def observed_bits(self):
        return 2*len(self.used)


