"""KNOW41 candidate/Bayesian mock-only qualification; no source first use."""
import json
import unittest
from know41_active_models_dev import (
    ActiveBayesian, ContradictionMemory, HAZARDS, _h_q,
)
from know41_active_identifiability_dev import expected_milli

class Know41ActiveModelsMock(unittest.TestCase):
    def test_hypotheses_are_frozen_conventional_controls_not_oracle_labels(self):
        for c in range(8):
            for a in (0, 1):
                for i in range(4):
                    self.assertAlmostEqual(
                        _h_q(c, a, i),
                        expected_milli(("CHAIN", "FORK")[i // 2], c, a, i % 2)/1000,
                        places=12)
        for h in HAZARDS:
            self.assertTrue(0 < h < 1)

    def test_observed_action_only_and_cold_future_decision_equivalence(self):
        for factory in (ContradictionMemory, ActiveBayesian):
            m = factory()
            actions = []
            a_at_64 = None
            for t in range(256):
                c = t % 8
                a = m.choose(t, c)
                actions.append(a)
                with self.assertRaisesRegex(ValueError, "UNWITNESSED"):
                    m.observe(t, c, 1-a, 1)
                # Deterministic *mock* generated by testing harness, not novel world.
                y = int((t * 11 + c * 5 + a * 7) % 13 < 6)
                m.observe(t, c, a, y)
                if t + 1 == 64 and isinstance(m, ContradictionMemory):
                    a_at_64 = [cell[:] for cell in m.a]
                if (t+1) in (64, 128, 192, 256):
                    raw = m.checkpoint()
                    self.assertLess(len(raw), 4096)
                    frozen = factory.cold(raw)
                    self.assertEqual(frozen.checkpoint(), raw)
                    for c0 in range(8):
                        for a0 in (0, 1):
                            self.assertAlmostEqual(m.prob(c0, a0), frozen.prob(c0, a0), places=12)
                    if t+1 < 256:
                        clone = factory.cold(raw)
                        expected_next = clone.choose(t+1, (t+1) % 8)
                        self.assertEqual(expected_next, frozen.choose(t+1, (t+1)%8))
                        # Return to prechoice cold state for subsequent loop.
                        frozen = factory.cold(raw)
                    m = frozen
                if a_at_64 is not None:
                    self.assertEqual(m.a, a_at_64)
            self.assertEqual(m.received, 256)
            self.assertGreater(sum(actions), 0)
            self.assertLess(sum(actions), 256)

    def test_bayesian_passive_action_does_not_identify_latent_hypothesis(self):
        m = ActiveBayesian()
        first = m.weights[:]
        # Under a0 all hypotheses have equal likelihood; hazard mixes uniform prior.
        for t in range(64):
            a = m.choose(t, t%8)
            # This explicitly tests the same public a0 observation class independently
            # of policy selection, by feeding an a0 counterfactual to an a0-only control.
            # A distinct comparator is used to enforce the actually chosen a0 witness.
            class Passive(ActiveBayesian):
                def choose(self, t, c):
                    from know41_active_identifiability_dev import key, need
                    need(t == self.received and self.pending is None, "PASSIVE")
                    key(c, 0)
                    self.pending = [t, c, 0]
                    return 0
            # Do not advance the model that may choose a1.
            break
        m = Passive()
        for t in range(64):
            c = t%8
            a = m.choose(t, c)
            self.assertEqual(a, 0)
            m.observe(t, c, a, t % 2)
        self.assertEqual(m.weights, first)

    def test_strict_custody_rejects_corruption(self):
        for factory in (ContradictionMemory, ActiveBayesian):
            m = factory()
            a = m.choose(0, 0)
            with self.assertRaisesRegex(ValueError, "UNWITNESSED"):
                m.observe(0, 0, a, True)
            m.observe(0, 0, a, 1)
            raw = m.checkpoint()
            for bad in ('{"kind":"x","kind":"x"}', '{"kind":"x"}'):
                with self.assertRaises(ValueError):
                    factory.cold(bad)
            corrupted = json.loads(raw)
            corrupted["received"] = 257
            with self.assertRaises(ValueError):
                factory.cold(json.dumps(corrupted, sort_keys=True, separators=(",", ":")))

if __name__ == "__main__":
    unittest.main()
