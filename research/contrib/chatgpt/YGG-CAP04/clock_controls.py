"""CAP04 prospective clock-only comparators, ENGINEERING FIXTURES ONLY.

Uses public current views, current intervention, chronological step and stage-2
witnessed s2. It NEVER conditions forecasts on the previous action, observation,
reward, hidden state, phase-label input, source identity, or witness identifier.
Counts are trained on the same genuinely observed action/consequence chronology.

Public time windows are derived only from the precommitted step boundaries.
No registered scientific seed or protected cohort is generated by this module.
"""
from __future__ import annotations

import json
import math

from yggdrasil.native_context_basis import canonical, digest, pin
from yggdrasil.native_paired_causal_contrast import state, arm

SCHEMA = "yggdrasil.cap04.clock-only-fixture-controls.v1"
ARMS = (
    "current_action_only_Beta",
    "public_clock_window_state_action_Beta",
    "public_clock_mod4_state_action_Beta",
    "public_clock_mod16_state_action_Beta",
    "public_absolute_clock_state_action_Beta",
)
STAGES = ("transition", "residual")
MAX_EVENTS = 2048
SHRINK = 4.0
WINDOWS = (32, 72)


def require(ok, reason):
    if not ok:
        raise ValueError("CAP04_CLOCK_CONTROL_" + reason)


def bit(x):
    require(type(x) is int and x in (0, 1), "BIT")
    return x


def window(t):
    require(type(t) is int and 0 <= t < MAX_EVENTS, "CLOCK")
    return int(t >= WINDOWS[0]) + int(t >= WINDOWS[1])


class ClockOnlyControls:
    """Five independently fitted, no-history-feature prequential Beta controls."""

    def __init__(self):
        self._events = []
        self._seen = set()
        self._pooled = {}
        self._counts = {name: {} for name in ARMS}

    @property
    def count(self):
        return len(self._events)

    @staticmethod
    def _mean(pair):
        yes, total = pair
        return (yes + 1.0) / (total + 2.0)

    def _keys(self, stage, st, chosen, s2, t):
        root = (stage, st, chosen, s2)
        return {
            "current_action_only_Beta": (stage, chosen, s2),
            "public_clock_window_state_action_Beta": root + (window(t),),
            "public_clock_mod4_state_action_Beta": root + (t % 4,),
            "public_clock_mod16_state_action_Beta": root + (t % 16,),
            "public_absolute_clock_state_action_Beta": root + (t,),
        }

    def forecast(self, views, chosen, stage, witnessed_s2=None, *, step):
        require(stage in STAGES, "STAGE")
        require(type(step) is int and step == self.count, "CLOCK")
        st, chosen = state(views), arm(chosen)
        if stage == "transition":
            require(witnessed_s2 is None, "FUTURE_SENSOR")
            s2 = None
        else:
            s2 = bit(witnessed_s2)
        root = (stage, st, chosen, s2)
        pooled = self._mean(self._pooled.get(root, (0, 0)))
        answers = {}
        for name, key in self._keys(stage, st, chosen, s2, step).items():
            yes, total = self._counts[name].get(key, (0, 0))
            if name == "current_action_only_Beta":
                p = self._mean((yes, total))
            else:
                p = (yes + SHRINK * pooled) / (total + SHRINK)
            require(0 <= p <= 1 and math.isfinite(p), "PROBABILITY")
            answers[name] = float(p)
        return answers

    def observe(self, identifier, views, chosen, s2, reward, post, *, step):
        require(pin(identifier) and identifier not in self._seen, "SOURCE_ID")
        require(type(step) is int and step == self.count, "CLOCK")
        st, pair = state(views), arm(chosen)
        s2, reward = bit(s2), bit(reward)
        require(type(post) is tuple and len(post) == 3 and
                all(type(x) is int and x in (0, 1) for x in post) and
                post[1] == s2, "POST")
        require(self.count < MAX_EVENTS, "CAPACITY")
        for stage, outcome, sensor in (
                ("transition", s2, None), ("residual", reward, s2)):
            root = (stage, st, pair, sensor)
            for name, key in self._keys(stage, st, pair, sensor, step).items():
                yes, total = self._counts[name].get(key, (0, 0))
                self._counts[name][key] = (yes + outcome, total + 1)
            yes, total = self._pooled.get(root, (0, 0))
            self._pooled[root] = (yes + outcome, total + 1)
        self._events.append((identifier, st, pair, s2, reward, post))
        self._seen.add(identifier)
        return self

    def checkpoint(self):
        return canonical({"schema": SCHEMA, "events": self._events})

    @classmethod
    def restore(cls, raw, expected_sha):
        require(type(raw) is bytes and pin(expected_sha) and
                digest(raw) == expected_sha, "COLD_HASH")
        try:
            doc = json.loads(raw.decode("ascii"))
            require(type(doc) is dict and set(doc) == {"schema", "events"} and
                    doc["schema"] == SCHEMA and type(doc["events"]) is list and
                    canonical(doc) == raw, "COLD_SCHEMA")
            model = cls()
            for t, event in enumerate(doc["events"]):
                identifier, st, action, s2, reward, post = event
                views = ((st[0], st[1]), (st[1], st[2]))
                model.observe(identifier, views, tuple(action), s2, reward,
                              tuple(post), step=t)
            require(model.checkpoint() == raw, "COLD_REPLAY")
            return model
        except (ValueError, TypeError, KeyError, IndexError, ArithmeticError,
                OverflowError, UnicodeError) as exc:
            raise ValueError("YGG_CAP04_CLOCK_COLD_REJECTED") from exc


def fixture_prequential_scores(rows):
    """Return engineering-only Brier summaries; never scientific thresholds."""
    require(type(rows) is tuple and len(rows) == 96, "FIXTURE_ONLY_BUDGET")
    control = ClockOnlyControls()
    by_arm = {name: {"novel": [], "cold_return": [], "pooled": []}
              for name in ARMS}
    for t, row in enumerate(rows):
        require(type(row) is dict and set(row) ==
                {"id", "views", "action", "s2", "y", "post"}, "ROW_FIELDS")
        before = control.checkpoint()
        first = control.forecast(row["views"], row["action"],
                                 "transition", step=t)
        # s2 is disclosed only after stage 1. reward remains hidden here.
        second = control.forecast(row["views"], row["action"],
                                  "residual", row["s2"], step=t)
        require(control.checkpoint() == before, "FORECAST_MUTATION")
        for name in ARMS:
            loss = ((first[name] - row["s2"])**2 +
                    (second[name] - row["y"])**2) / 2.0
            if 48 <= t < 96:
                by_arm[name]["pooled"].append(loss)
                by_arm[name]["novel" if t < 72 else "cold_return"].append(loss)
        control.observe(row["id"], row["views"], row["action"],
                        row["s2"], row["y"], row["post"], step=t)
    means = {name: {phase: math.fsum(losses) / len(losses)
                    for phase, losses in phase_data.items()}
             for name, phase_data in by_arm.items()}
    return {"classification": "ENGINEERING_FIXTURE_ONLY",
            "rows_verified": control.count,
            "means": means,
            "checkpoint_sha256": digest(control.checkpoint())}
