"""WSP99 original-free, one-shot full-budget strong-control DEV fixture pilot."""
from __future__ import annotations
import argparse
import json
import math
import time
from controls import GradientMemoryless, GradientTanhRNN, SymbolicFiniteState
from gru_control import GradientGRU16
from source_eval import _sha256, make_fixture_sources, make_fixture_heldout_plan, make_predictions, score_fixture_predictions

SEEDS = (11, 17, 23)
FAMILIES = {"rnn16": GradientTanhRNN, "gru16": GradientGRU16, "memoryless16": GradientMemoryless}


def _source_fit_memoryless(model, episodes):
    return sum(int(int(prob > .5) == bit)
               for episode in episodes for x, action, y in episode
               for prob, bit in zip(model.probability(x, action), y)) / (len(episodes) * 4 * 6)


def _memoryless_rollout(model, initial, actions):
    x = initial
    states = []
    for a in actions:
        x = tuple(int(p > .5) for p in model.probability(x, a))
        states.append(x)
    return tuple(states)


def _predict(model, family, x, actions):
    if family == "symbolic":
        return model.rollout(x, actions)
    if family == "memoryless16":
        return _memoryless_rollout(model, x, actions)
    return tuple(state for state, _p in model.rollout(x, actions))


def _train_family(source, family):
    candidates = []
    chosen = None
    for seed in SEEDS:
        model = FAMILIES[family](seed)
        start = time.process_time_ns()
        loss = model.train(source)
        cpu_ns = time.process_time_ns() - start
        fit = (_source_fit_memoryless(model, source)
               if family == "memoryless16" else model.source_fit(source))
        if model.epochs_trained != 1800 or not (math.isfinite(loss) and 0 <= fit <= 1):
            raise ValueError("strong-control full training qualification failed")
        candidates.append({"seed": seed, "source_fit": fit, "source_bce": loss,
                           "epochs": 1800, "train_cpu_ns": cpu_ns})
        key = (loss, -fit, seed)
        if chosen is None or key < chosen[0]:
            chosen = (key, model, seed, fit)
    return candidates, chosen[1], chosen[2], chosen[3]


def run():
    wall0, cpu0 = time.perf_counter_ns(), time.process_time_ns()
    pending = []
    for fixture_id in range(8):
        bundle = make_fixture_sources(fixture_id)
        plan = make_fixture_heldout_plan(bundle)
        source = bundle["passive"] + bundle["active"]
        start = time.process_time_ns()
        symbolic = SymbolicFiniteState(source)
        info = {"symbolic": {"source_fit": symbolic.source_accuracy,
                             "survivors_per_latch": symbolic.candidate_counts,
                             "fit_cpu_ns": time.process_time_ns() - start}}
        predictions = {"symbolic": make_predictions(
            plan, lambda x, a: _predict(symbolic, "symbolic", x, a))}
        for family in ("rnn16", "gru16", "memoryless16"):
            records, selected, seed, fit = _train_family(source, family)
            info[family] = {"source_fit": fit, "selected_by_source_seed": seed,
                            "all_frozen_seed_fits": records}
            predictions[family] = make_predictions(
                plan, lambda x, a, model=selected, label=family: _predict(model, label, x, a))
        frozen = _sha256({
            "fixture": fixture_id, "source_sha256": bundle["source_sha256"],
            "plan_sha256": plan["plan_sha256"],
            "predictions": {name: _sha256(pred) for name, pred in predictions.items()}})
        pending.append((bundle, plan, info, predictions, frozen))
    # No heldout truth has been generated by this script yet; all methods,
    # fixtures and seeds have been selected from source-only losses.
    seal = _sha256([(b["fixture_id"], frozen)
                    for b, _plan, _info, _prediction, frozen in pending])
    print("WSP99_DEV_ALL_METHOD_PREDICTIONS_FROZEN=" + seal, flush=True)
    worlds = []
    for b, plan, info, predictions, frozen in pending:
        scores = {}
        for name, pred in predictions.items():
            score = score_fixture_predictions(b, plan, pred)
            scores[name] = {
                "terminal": score["terminal_accuracy"],
                "step2": score["per_step_correct"][1] / score["per_step_total"],
                "step3": score["per_step_correct"][2] / score["per_step_total"],
                "source_fit": info[name]["source_fit"],
                "reward_brier": score["reward_brier"],
                "predictions_sha256": score["prediction_sha256"],
            }
        worlds.append({
            "fixture": b["fixture_id"], "source_sha256": b["source_sha256"],
            "plan_sha256": plan["plan_sha256"], "pre_score_methods_sha256": frozen,
            "delayed_pairs": score["delayed_pair_count"],
            "scores": scores, "training": info,
        })
    summary = {}
    for name in ("symbolic", "rnn16", "gru16", "memoryless16"):
        summary[name] = {
            "mean_source_fit": sum(w["scores"][name]["source_fit"] for w in worlds) / 8,
            "minimum_source_fit": min(w["scores"][name]["source_fit"] for w in worlds),
            "mean_terminal": sum(w["scores"][name]["terminal"] for w in worlds) / 8,
            "maximum_terminal": max(w["scores"][name]["terminal"] for w in worlds),
        }
    strongest = max(summary[k]["maximum_terminal"] for k in ("symbolic", "rnn16", "gru16"))
    recurrent = max(summary[k]["mean_terminal"] for k in ("rnn16", "gru16"))
    history_gain = recurrent - summary["memoryless16"]["mean_terminal"]
    min_neural_fit = min(summary[k]["minimum_source_fit"] for k in ("rnn16", "gru16"))
    if strongest > .95:
        classification = "DEV_CEILING"
    elif min_neural_fit < .95:
        classification = "DEV_LEARNING_BLOCKED"
    elif .65 <= strongest <= .95 and history_gain >= .08:
        classification = "DEV_HEADROOM"
    else:
        classification = "DEV_NEGATIVE"
    report = {
        "schema": "wsp99.fixture-headroom-pilot.v1",
        "classification": classification, "development_only": True,
        "scientific_superiority": False, "frozen_prediction_receipt": seal,
        "summary": summary, "worlds": worlds,
        "maximum_strong_terminal": strongest, "history_gain": history_gain,
        "delayed_pair_fraction": sum(w["delayed_pairs"] for w in worlds) / 192,
        "process_cpu_ns": time.process_time_ns() - cpu0,
        "process_wall_ns": time.perf_counter_ns() - wall0,
        "original_public_untouched": True, "original_reserved_untouched": True,
    }
    print("WSP99_DEV_HEADROOM_RESULT=" + json.dumps(
        report, sort_keys=True, separators=(",", ":"), allow_nan=False), flush=True)
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixture-only", required=True, action="store_true")
    parser.parse_args()
    run()
