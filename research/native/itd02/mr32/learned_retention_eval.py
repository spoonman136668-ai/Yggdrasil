"""Held-out synthetic memory-retention experiment for MR32-H.

FIT labels train a utility score; TRANSFER uses disjoint memory keys and no
feedback. Compare the learned active set against deterministic recency-only
and evidence-only top-7 baselines on the same 16 held-out records.
This is a synthetic mechanism falsification, not a real-task benchmark.
"""
from __future__ import annotations
import json
from learned_memory_allocator import LearnedMemoryAllocator, ACTIVE


PROFILES = []
for high_evidence in (False, True):
    for low_error in (False, True):
        for low_contradiction in (False, True):
            PROFILES.append((
                64 if high_evidence else 2,
                0.0 if low_error else 1.0,
                0.0 if low_contradiction else 1.0,
                int(sum((high_evidence, low_error, low_contradiction)) >= 2),
            ))


def representation(i):
    return tuple(1.0 if j == i % 16 else 0.0 for j in range(16))


def run():
    fit = LearnedMemoryAllocator()
    for epoch in range(30):
        for i, (evidence, error, contradiction, label) in enumerate(PROFILES):
            key = f"fit-{i}"
            if not any(m.occupied and m.key == key for m in fit.memories):
                fit.insert(key, representation(i), evidence_count=evidence,
                           prediction_error=error, contradiction_rate=contradiction)
            fit.mark_use(key)
            fit.observe_task_outcome(key, float(label))

    # Transfer only the learned scoring weights; no FIT memory or label survives.
    held = LearnedMemoryAllocator()
    held.weights = list(fit.weights)
    cohort = []
    for repeat in range(2):
        for i, (evidence, error, contradiction, label) in enumerate(PROFILES):
            key = f"eval-{repeat}-{i}"
            held.insert(key, representation(100 + repeat * 8 + i),
                        evidence_count=evidence, prediction_error=error,
                        contradiction_rate=contradiction)
            cohort.append({"key": key, "useful": label, "evidence": evidence})

    by_key = {m.key: m for m in held.memories if m.occupied}
    learned = {m.key for m in held.memories if m.occupied and m.active}
    recency = {r["key"] for r in sorted(
        cohort, key=lambda r: by_key[r["key"]].last_used, reverse=True)[:ACTIVE]}
    evidence = {r["key"] for r in sorted(
        cohort, key=lambda r: (-r["evidence"], r["key"]))[:ACTIVE]}

    def metric(selected):
        hits = sum(r["useful"] for r in cohort if r["key"] in selected)
        return {"useful_retained": hits, "selected": len(selected),
                "precision_at_7": hits / ACTIVE}

    positives = sum(r["useful"] for r in cohort)
    return {
        "schema": "yggdrasil.mr32.heldout-retention-eval.v1",
        "classification": "SYNTHETIC_FIT_TRANSFER_MECHANISM_CHECK_NOT_SCIENTIFIC_EFFICACY",
        "fit": {"profiles": len(PROFILES), "epochs": 30,
                "feedback_events": fit.feedback_count},
        "transfer": {"records": len(cohort), "useful_records": positives,
                     "feedback_events": held.feedback_count,
                     "active_budget": ACTIVE},
        "results": {"learned_utility": metric(learned),
                    "fixed_recency": metric(recency),
                    "evidence_only": metric(evidence)},
        "learned_weights": list(fit.weights),
        "limitations": [
            "Synthetic usefulness labels are generated by a fixed majority rule over three metadata features.",
            "The FIT/TRANSFER records are disjoint by key, but share the same synthetic generating rule.",
            "No future query, causal world, reward process, cold-restart interference or unfamiliar task family is represented.",
            "The metadata basis and linear utility learner are hand-designed; only scorer weights are learned.",
            "One deterministic cohort and one seed; no confidence interval or statistical claim.",
        ],
    }


if __name__ == "__main__":
    print(json.dumps(run(), sort_keys=True, indent=2, allow_nan=False))
