"""YGG-CAP04: source-induced history-conditioned causal readout (research only).

Supplemental to original cumulative Yggdrasil: no native weights, historical
episodes or six JEPA heads are overwritten. Forecasts see only genuinely
witnessed public action/consequence history, never private source metadata.
Registered scientific source is never generated by this module.
"""
from __future__ import annotations

import json
import math
from yggdrasil.native_context_basis import canonical, digest, pin
from yggdrasil.native_paired_causal_contrast import state, arm

SCHEMA = "yggdrasil.cap04.native-predictive-state-split.v1"
SCHEMA_DIRECT = "yggdrasil.cap04.native-predictive-state-direct-reward-shadow.v1"
SCHEMA_RECENT32 = "yggdrasil.cap04.native-direct-reward-recent32-shadow.v1"
ROUTING_MODES = ("cumulative", "recent32")
RECENT_WINDOW = 32
RECENT_LOG_GATE = 2.5
REWARD_MODES = ("xor", "direct")
KINDS = ("transition", "residual")
FEATURES = ("previous_pair", "previous_post", "previous_reward", "previous_pair_post")
SHRINK = 4.0
LOG_PENALTY = 5.0
MIN_EVIDENCE = 16
MAX_EVENTS = 2048


def require(ok, tag):
    if not ok:
        raise ValueError("CAP04_" + tag)


def bit(x):
    require(type(x) is int and x in (0, 1), "BIT")
    return x


class PredictiveStateSplit:
    """Fixed-penalty prequential causal history feature selection."""

    def __init__(self, *, sham=False, reward_mode="xor",
                 routing_mode="cumulative"):
        require(type(reward_mode) is str and reward_mode in REWARD_MODES,
                "REWARD_MODE")
        require(type(routing_mode) is str and routing_mode in ROUTING_MODES
                and (routing_mode == "cumulative" or reward_mode == "direct"),
                "ROUTING_MODE")
        self.sham = bool(sham)
        self.reward_mode = reward_mode
        self.routing_mode = routing_mode
        self._events = []
        self._seen = set()
        self._pool = {}
        self._split = {}
        self._evidence = {k: {f: 0.0 for f in FEATURES} for k in KINDS}
        self._qualified = {k: 0 for k in KINDS}
        # RD04 opt-in only; never written into old v1/v2 checkpoint schemas.
        # Evidence is replay-derived from genuine witnessed source events.
        self._recent_gains = {k: {f: [] for f in FEATURES} for k in KINDS}

    @property
    def count(self):
        return len(self._events)

    def _feature_values(self):
        # Sham deliberately uses the wrong historical episode.
        lag = 3 if self.sham else 1
        if len(self._events) < lag:
            return None
        previous = self._events[-lag]
        pair, post, reward = previous[2], previous[5], previous[4]
        return {
            "previous_pair": pair,
            "previous_post": post,
            "previous_reward": reward,
            "previous_pair_post": (pair, post),
        }

    def _conditioned_state(self, kind, st, s2):
        # In the opt-in RD01 mode the terminal reward can have an arbitrary
        # observed-sensor conditional, instead of being forced to XOR s2.
        # The original CAP04 XOR mode continues to use the same three-bit
        # state/key and byte-identical legacy checkpoint schema.
        if kind == "residual" and self.reward_mode == "direct":
            return st + (bit(s2),)
        return st

    @staticmethod
    def _mean(counts):
        yes, n = counts
        return (yes + 1.0) / (n + 2.0)

    def _estimate(self, kind, st, chosen, values, feature=None):
        base_key = (kind, st, chosen)
        pooled = self._mean(self._pool.get(base_key, (0, 0)))
        if feature is None or values is None:
            return pooled
        key = (kind, st, chosen, feature, values[feature])
        yes, n = self._split.get(key, (0, 0))
        return (yes + SHRINK * pooled) / (n + SHRINK)

    def _winner(self, kind, values):
        if values is None or self._qualified[kind] < MIN_EVIDENCE:
            return None
        if self.routing_mode == "recent32":
            scores = {f: math.fsum(self._recent_gains[kind][f])
                      for f in FEATURES}
            f = max(FEATURES, key=lambda name:
                    (scores[name], -FEATURES.index(name)))
            return f if scores[f] >= RECENT_LOG_GATE else None
        f = max(FEATURES, key=lambda name:
                (self._evidence[kind][name], -FEATURES.index(name)))
        if self._evidence[kind][f] < LOG_PENALTY:
            return None
        return f

    def selected_feature(self, stage):
        require(stage in KINDS, "STAGE")
        return self._winner(stage, self._feature_values())

    def forecast(self, views, chosen, stage, witnessed_s2=None):
        st = state(views)
        pair = arm(chosen)
        require(stage in KINDS, "STAGE")
        if stage == "transition":
            require(witnessed_s2 is None, "FIRST_STAGE_FUTURE_SENSOR")
        else:
            bit(witnessed_s2)
        values = self._feature_values()
        feature = self._winner(stage, values)
        conditioned = self._conditioned_state(stage, st, witnessed_s2)
        probability = self._estimate(stage, conditioned, pair, values, feature)
        if (stage == "residual" and self.reward_mode == "xor"
                and witnessed_s2 == 1):
            probability = 1.0 - probability
        require(0 <= probability <= 1 and math.isfinite(probability),
                "PROBABILITY")
        return float(probability)

    @classmethod
    def from_native_events(cls, native_events, *, sham=False,
                           reward_mode="xor", routing_mode="cumulative"):
        """Load genuine seven-field historical events without modifying native.

        The early native sensor pair could contain two independent public
        views; only the new supplemental readout uses their 3-bit projection.
        The native original/checkpoint remains intact and separately pinned.
        """
        obj = cls(sham=sham, reward_mode=reward_mode,
                  routing_mode=routing_mode)
        for event in native_events:
            require(type(event) is tuple and len(event) in (6, 7),
                    "ORIGINAL_PUBLIC_ROW")
            if len(event) == 6:
                ident, views, a, s2, b, y = event
                post = None  # Original native ledger did not witness a post triple.
            else:
                ident, views, a, s2, b, y, post = event
            obj.observe(ident, views, (a, b), s2, y, post, legacy=True)
        return obj

    def observe(self, identifier, views, chosen, s2, y, post, *, legacy=False):
        require(pin(identifier), "SOURCE_ID")
        if legacy:
            require(type(views) is tuple and len(views) == 2 and
                    all(type(v) is tuple and len(v) == 2 for v in views) and
                    all(type(x) is int and x in (0, 1) for v in views for x in v),
                    "LEGACY_SENSOR_VIEWS")
            st = (views[0][0], views[0][1], views[1][1])
        else:
            st = state(views)
        pair = arm(chosen)
        s2 = bit(s2)
        y = bit(y)
        if post is None:
            require(legacy, "MISSING_POST_NOT_LEGACY")
        else:
            require(type(post) is tuple and len(post) == 3 and
                    all(type(x) is int and x in (0, 1) for x in post) and
                    post[1] == s2, "OBSERVED_POST")
        require(identifier not in self._seen, "DUPLICATE_OR_CONFLICT")
        require(self.count < MAX_EVENTS, "EVENT_CAPACITY")
        values = self._feature_values()
        labels = {"transition": s2,
                  "residual": y if self.reward_mode == "direct" else y ^ s2}
        for kind in KINDS:
            label = labels[kind]
            conditioned = self._conditioned_state(kind, st, s2)
            base_key = (kind, conditioned, pair)
            pooled = self._estimate(kind, conditioned, pair, None)
            if values is not None:
                self._qualified[kind] += 1
                for feature in FEATURES:
                    split = self._estimate(kind, conditioned, pair, values, feature)
                    p0 = max(1e-12, min(1 - 1e-12, pooled))
                    p1 = max(1e-12, min(1 - 1e-12, split))
                    gain = (math.log(p1 if label else 1 - p1) -
                            math.log(p0 if label else 1 - p0))
                    self._evidence[kind][feature] += gain
                    if self.routing_mode == "recent32":
                        recent = self._recent_gains[kind][feature]
                        recent.append(gain)
                        if len(recent) > RECENT_WINDOW:
                            recent.pop(0)
                    key = (kind, conditioned, pair, feature, values[feature])
                    yes, n = self._split.get(key, (0, 0))
                    self._split[key] = (yes + label, n + 1)
            yes, n = self._pool.get(base_key, (0, 0))
            self._pool[base_key] = (yes + label, n + 1)
        self._events.append((identifier, st, pair, s2, y, post))
        self._seen.add(identifier)
        return self

    def checkpoint(self):
        if self.reward_mode == "xor":
            # Exact legacy schema and bytes for all original CAP04 weights.
            return canonical({"schema": SCHEMA, "sham": self.sham,
                              "events": self._events})
        if self.routing_mode == "recent32":
            return canonical({"schema": SCHEMA_RECENT32, "sham": self.sham,
                              "reward_mode": "direct",
                              "routing_mode": "recent32",
                              "events": self._events})
        return canonical({"schema": SCHEMA_DIRECT, "sham": self.sham,
                          "reward_mode": "direct", "events": self._events})

    @classmethod
    def restore(cls, raw, expected_sha):
        require(type(raw) is bytes and pin(expected_sha) and
                digest(raw) == expected_sha, "COLD_HASH")
        try:
            doc = json.loads(raw.decode("ascii"))
            require(type(doc) is dict and type(doc.get("sham")) is bool
                    and type(doc.get("events")) is list
                    and canonical(doc) == raw, "COLD_SCHEMA")
            if doc.get("schema") == SCHEMA:
                require(set(doc) == {"schema", "sham", "events"},
                        "COLD_SCHEMA")
                reward_mode = "xor"
                routing_mode = "cumulative"
            elif doc.get("schema") == SCHEMA_DIRECT:
                require(set(doc) == {"schema", "sham", "reward_mode", "events"}
                        and doc["reward_mode"] == "direct", "COLD_SCHEMA")
                reward_mode = "direct"
                routing_mode = "cumulative"
            else:
                require(doc.get("schema") == SCHEMA_RECENT32 and
                        set(doc) == {"schema", "sham", "reward_mode",
                                     "routing_mode", "events"} and
                        doc["reward_mode"] == "direct" and
                        doc["routing_mode"] == "recent32", "COLD_SCHEMA")
                reward_mode = "direct"
                routing_mode = "recent32"
            learner = cls(sham=doc["sham"], reward_mode=reward_mode,
                          routing_mode=routing_mode)
            for ident, st, pair, s2, y, post in doc["events"]:
                views = ((st[0], st[1]), (st[1], st[2]))
                learner.observe(ident, views, tuple(pair), s2, y,
                                tuple(post) if post is not None else None,
                                legacy=(post is None))
            require(learner.checkpoint() == raw, "COLD_REPLAY")
            return learner
        except (KeyError, IndexError, TypeError, ValueError, OverflowError,
                UnicodeError, ArithmeticError) as exc:
            raise ValueError("YGG_CAP04_COLD_REJECTED") from exc
